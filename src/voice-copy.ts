export function speechProblemText(message: string, locale: UiLocale): string {
  if (locale === 'de') return message;
  if (Object.hasOwn(serviceErrors, message)) return serviceErrors[message];
  const http = /^Der Sprachanbieter hat die Anfrage abgelehnt \(HTTP (\d{3})\)\. Bitte Endpunkt, Modell und Modus prüfen\.$/.exec(message);
  return http ? `The speech provider rejected the request (HTTP ${http[1]}). Check the endpoint, model and mode.` : message;
}
